// Utilitário de busca fuzzy instantânea (0ms) com tolerância a acentos, prefixos e erros
export function searchCityStreets(query: string, limit = 10): CityStreet[] {
  if (!query || query.trim().length === 0) return [];
  
  const clean = (s: string) =>
    s.toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/^(rua|avenida|av\.?|r\.?|travessa|trav\.?|alameda|rodovia)\s+/i, "")
      .replace(/[^a-z0-9]/g, "");

  const qClean = clean(query);
  if (!qClean) return [];

  const rawQ = query.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim();
  const words = rawQ.split(/\s+/).filter(w => w.length > 1);

  const scored: Array<{ street: CityStreet; score: number }> = [];
  const seenNames = new Set<string>();

  for (const st of PRIMAVERA_DO_LESTE_STREETS) {
    const key = st.name.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    if (seenNames.has(key)) continue;

    const stClean = clean(st.name);
    const stRaw = key;
    const bairroRaw = (st.bairro || "").toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");

    let score = 0;

    // Match exato limpo (ex: "poxoreo" -> "Rua Poxoréo")
    if (stClean === qClean) {
      score += 100;
    } else if (stClean.startsWith(qClean)) {
      score += 80;
    } else if (stRaw.includes(rawQ)) {
      score += 65;
    } else if (stClean.includes(qClean)) {
      score += 50;
    } else {
      // Match por palavras (ex: "sao paulo", "ari krief", "poxoreo")
      let matchedWords = 0;
      for (const w of words) {
        if (stRaw.includes(w) || bairroRaw.includes(w)) {
          matchedWords++;
        }
      }
      if (matchedWords === words.length && words.length > 0) {
        score += 45 * matchedWords;
      } else if (matchedWords > 0) {
        score += 20 * matchedWords;
      }
    }

    if (score > 0) {
      seenNames.add(key);
      scored.push({ street: st, score });
    }
  }

  scored.sort((a, b) => b.score - a.score || a.street.name.localeCompare(b.street.name, 'pt-BR'));
  return scored.slice(0, limit).map(item => item.street);
}
